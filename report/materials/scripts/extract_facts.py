"""
Pulls extra facts for the report out of the raw files in results/, the ones summary.md doesn't show.

    python report/materials/scripts/extract_facts.py      # from the repo root

Writes report/materials/facts/derived-facts.md and the CSVs behind the figures. Every number
comes from a file in results/; nothing is estimated. Read the output as evidence, not as analysis.
"""
from __future__ import annotations

import csv
import json
import re
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RES = ROOT / "results"
OUT = ROOT / "report" / "materials"
RUNS = ["20261124-132305-cores-1-8", "20261124-132305-all-events", "20261124-132305-FR",
        "20261124-132305-NL", "20261124-132305-ETR", "20261117-221652"]


def mem_mib(s: str) -> float:
    """'1.067GiB / 7.748GiB' -> MiB used."""
    used = s.split("/")[0].strip()
    num = float(re.match(r"[\d.]+", used).group())
    return num * 1024 if "GiB" in used else num / 1024 if "KiB" in used else num


def cpu_table(run_dir: Path) -> list[dict]:
    rows = []
    for f in sorted(run_dir.glob("cpu-c*-r1.csv"), key=lambda p: int(re.search(r"c(\d+)", p.name).group(1))):
        cores = int(re.search(r"c(\d+)", f.name).group(1))
        by = {}
        with open(f) as fh:
            for r in csv.DictReader(fh):
                try:
                    by.setdefault(r["container"], []).append((float(r["cpu_percent"]), mem_mib(r["mem"])))
                except (ValueError, AttributeError, KeyError):
                    pass
        for name, vals in sorted(by.items()):
            cpu = [v[0] for v in vals]
            rows.append({"cores": cores, "container": name, "samples": len(vals),
                         "cpu_mean": round(st.mean(cpu), 1), "cpu_max": round(max(cpu), 1),
                         "mem_peak_mib": round(max(v[1] for v in vals))})
    return rows


def vertex_table(run_dir: Path) -> list[dict]:
    rows = []
    for f in sorted(run_dir.glob("job-c*-r1.json"), key=lambda p: int(re.search(r"c(\d+)", p.name).group(1))):
        cores = int(re.search(r"c(\d+)", f.name).group(1))
        job = json.load(open(f))
        for v in job["vertices"]:
            name = v["name"]
            short = "source+router" if name.startswith("Source") else "window" if name.startswith("5-min") else "ema+sinks"
            key = "write-records" if short == "source+router" else "read-records"
            per = [s["metrics"][key] for s in v["subtasks"]]
            m = v["metrics"]
            total = m["accumulated-busy-time"] + m["accumulated-idle-time"] + m["accumulated-backpressured-time"]
            rows.append({"cores": cores, "task": short, "parallelism": v["parallelism"], "records": sum(per),
                         "per_subtask": per, "max_over_mean": round(max(per) / st.mean(per), 2),
                         "busy_pct": round(100 * m["accumulated-busy-time"] / total, 1) if total else None,
                         "backpressured_pct": round(100 * m["accumulated-backpressured-time"] / total, 1) if total else None,
                         "idle_pct": round(100 * m["accumulated-idle-time"] / total, 1) if total else None})
    return rows


def md_table(rows: list[dict], cols: list[str]) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(f"{r[c]:,}" if isinstance(r[c], int) else str(r[c]) for c in cols) + " |")
    return "\n".join(out)


def main():
    (OUT / "facts").mkdir(parents=True, exist_ok=True)
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    lines = ["# Derived facts from the raw result files",
             "",
             "Generated by `report/materials/scripts/extract_facts.py` from `results/`. These are the numbers",
             "`results/summary.md` doesn't print: per-container CPU and memory, and per-subtask record counts",
             "and busy / backpressured / idle time for each Flink task. Numbers only.",
             "",
             "Busy, backpressured and idle are Flink's `accumulated-*-time` metrics summed over subtasks, as",
             "a share of their total. Source records are what each source subtask read from Kafka (after the",
             "router dropped non-trades); window and EMA records are what each subtask received over the hash shuffle.",
             ""]
    all_vertex = []
    for run in RUNS:
        d = RES / "scalability" / run
        if not d.exists():
            continue
        prod = json.load(open(d / "producer.json"))
        lines += [f"## {run}", "",
                  f"Producer fill: {prod['events']:,} events in {prod['seconds']} s ({prod['events_per_second']:,} events/s), "
                  f"events={prod['events_kind']}, exchanges={prod['exchanges'] or 'all'}.", ""]
        vt = vertex_table(d)
        for r in vt:
            r["run"] = run
        all_vertex += vt
        lines += ["### Flink tasks (repeat 1)", "",
                  md_table(vt, ["cores", "task", "records", "max_over_mean", "busy_pct", "backpressured_pct", "idle_pct"]),
                  "", "Records per subtask:", ""]
        for r in vt:
            lines.append(f"- {r['cores']} cores, {r['task']}: " + ", ".join(f"{x:,}" for x in r["per_subtask"]))
        src = [r for r in vt if r["task"] == "source+router"]
        if src:
            lines += ["", f"Trades that left the router (summed over source subtasks): {src[0]['records']:,}. "
                          f"Producer sent {prod['events']:,} events, so {prod['events'] - src[0]['records']:,} were "
                          f"counted and dropped by the router (placeholder-time trades, malformed rows, and for "
                          f"events=all the quotes and housekeeping events)."]
        ct = cpu_table(d)
        lines += ["", "### Containers during the measured run (docker stats, about 1 sample per 2 s)", "",
                  "CPU is in percent of one core (400 = four cores fully busy).", "",
                  md_table(ct, ["cores", "container", "samples", "cpu_mean", "cpu_max", "mem_peak_mib"]), ""]
        with open(OUT / "tables" / f"containers-{run}.csv", "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(ct[0].keys()))
            w.writeheader()
            w.writerows(ct)

    with open(OUT / "tables" / "flink-subtasks.csv", "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["run", "cores", "task", "subtask", "records"])
        for r in all_vertex:
            for i, x in enumerate(r["per_subtask"]):
                w.writerow([r["run"], r["cores"], r["task"], i, x])

    # Repeats of the 17 Nov run, for the spread
    rr = list(csv.DictReader(open(RES / "scalability" / "20261117-221652" / "runs.csv")))
    lines += ["## Repeat spread, 17 Nov run (3 repeats per core count)", "",
              "| cores | run_ms per repeat | mean s | std s | min-max range |", "|---|---|---|---|---|"]
    for c in sorted({int(r["cores"]) for r in rr}):
        ms = [int(r["run_ms"]) for r in rr if int(r["cores"]) == c]
        lines.append(f"| {c} | {', '.join(f'{m:,}' for m in ms)} | {st.mean(ms)/1000:.1f} | {st.stdev(ms)/1000:.1f} | "
                     f"{(max(ms)-min(ms))/1000:.1f} s ({100*(max(ms)-min(ms))/st.mean(ms):.0f}%) |")

    (OUT / "facts" / "derived-facts.md").write_text("\n".join(lines) + "\n")
    print("wrote", OUT / "facts" / "derived-facts.md")


if __name__ == "__main__":
    main()
